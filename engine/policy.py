def saturation_grade(saturation):
    """포화도 값 -> (등급, 라벨)."""
    if saturation is None:
        return (None, "미입력")
    for cut, grade, label in SATURATION_GRADES:
        if saturation >= cut:
            return (grade, label)
    return ("D", "포화 · 레드오션")


def axis_grade(score100):
    """0~100 점수 -> 등급 문자."""
    if score100 is None:
        return None
    for cut, grade in AXIS_GRADES:
        if score100 >= cut:
            return grade
    return "D"
